package main

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

const (
	beginMarker = "<!-- BEGIN GENERATED: parity -->"
	endMarker   = "<!-- END GENERATED: parity -->"
)

func readLines(path string) ([]string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, err
	}
	defer f.Close()
	var out []string
	sc := bufio.NewScanner(f)
	sc.Buffer(make([]byte, 0, 64*1024), 4*1024*1024)
	for sc.Scan() {
		out = append(out, sc.Text())
	}
	return out, sc.Err()
}

func (m *Matrix) countsByKind() map[string]map[string]int {
	out := map[string]map[string]int{}
	disp := map[string]string{}
	for _, r := range m.Matrix {
		disp[r.ID] = r.Disposition
	}
	for _, r := range m.Inventory {
		if out[r.Kind] == nil {
			out[r.Kind] = map[string]int{}
		}
		out[r.Kind][disp[r.ID]]++
		out[r.Kind]["total"]++
	}
	return out
}

func esc(s string) string {
	return strings.ReplaceAll(s, "|", "\\|")
}

func (m *Matrix) GenerateAppendix() string {
	var b strings.Builder
	byKind := m.countsByKind()
	b.WriteString(beginMarker + "\n")
	b.WriteString("<!-- Generated by `make parity` from testdata/parity/*.tsv. Do not edit by hand. -->\n")
	b.WriteString("### A.2 Counts\n\n")
	b.WriteString("| Kind | equivalent | adaptation | extension | n/a | defect-not-copied | total |\n")
	b.WriteString("|---|---:|---:|---:|---:|---:|---:|\n")
	tot := map[string]int{}
	for _, k := range kinds {
		c := byKind[k]
		fmt.Fprintf(&b, "| %s | %d | %d | %d | %d | %d | %d |\n",
			k, c["equivalent"], c["adaptation"], c["extension"], c["n/a"], c["defect-not-copied"], c["total"])
		for _, d := range []string{"equivalent", "adaptation", "extension", "n/a", "defect-not-copied", "total"} {
			tot[d] += c[d]
		}
	}
	fmt.Fprintf(&b, "| **total** | %d | %d | %d | %d | %d | %d |\n",
		tot["equivalent"], tot["adaptation"], tot["extension"], tot["n/a"], tot["defect-not-copied"], tot["total"])
	b.WriteString("\n### A.3 N/A register\n\n")
	b.WriteString("Every row below is an explicit, documented N/A. A **refusal** names the exact stderr line and exit code; an **absence** names what never renders and what happens instead. Every row cites at least one AC.\n\n")
	b.WriteString("| ID | Surface | Proof | Behaviour | Spec |\n")
	b.WriteString("|---|---|---|---|---|\n")
	inv := map[string]InventoryRow{}
	for _, r := range m.Inventory {
		inv[r.ID] = r
	}
	for _, r := range m.Matrix {
		if r.Disposition != "n/a" {
			continue
		}
		proof := "absence"
		low := strings.ToLower(r.Behaviour)
		if strings.Contains(low, "exit 2") && strings.Contains(low, "xbpretty:") {
			proof = "refusal"
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s |\n", r.ID, esc(inv[r.ID].Surface), proof, esc(r.Behaviour), esc(r.Spec))
	}
	b.WriteString("\n### A.4 Deviation register\n\n")
	b.WriteString("Every row that is not `equivalent` and not `n/a`: the delta from nala and the xbps input or superset that causes it.\n\n")
	b.WriteString("| ID | Surface | Disposition | xbps mechanism | Evidence | Spec |\n")
	b.WriteString("|---|---|---|---|---|---|\n")
	for _, r := range m.Matrix {
		if r.Disposition == "equivalent" || r.Disposition == "n/a" {
			continue
		}
		fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s |\n", r.ID, esc(inv[r.ID].Surface), r.Disposition, esc(r.Xbps), esc(r.Evidence), esc(r.Spec))
	}
	b.WriteString(endMarker)
	return b.String()
}

func (m *Matrix) GenerateMarkdown() string {
	var b strings.Builder
	byKind := m.countsByKind()
	inv := map[string]InventoryRow{}
	for _, r := range m.Inventory {
		inv[r.ID] = r
	}
	b.WriteString("# nala v0.18.2 → xbps parity matrix\n\n")
	b.WriteString("**Generated** by `make parity` from `testdata/parity/nala-v0.18.2.tsv` and `testdata/parity/matrix.tsv`. Do not edit this file by hand; edit a TSV and regenerate.\n\n")
	fmt.Fprintf(&b, "%d rows; **%d explicit N/A**. The spec's Appendix A.1 carries the rules; Appendix A.2–A.4 and this file are the generated renderings.\n\n", len(m.Matrix), m.NACount())
	b.WriteString("## Summary\n\n")
	b.WriteString("| Kind | equivalent | adaptation | extension | n/a | defect-not-copied | total |\n")
	b.WriteString("|---|---:|---:|---:|---:|---:|---:|\n")
	tot := map[string]int{}
	for _, k := range kinds {
		c := byKind[k]
		fmt.Fprintf(&b, "| %s | %d | %d | %d | %d | %d | %d |\n",
			k, c["equivalent"], c["adaptation"], c["extension"], c["n/a"], c["defect-not-copied"], c["total"])
		for _, d := range []string{"equivalent", "adaptation", "extension", "n/a", "defect-not-copied", "total"} {
			tot[d] += c[d]
		}
	}
	fmt.Fprintf(&b, "| **total** | %d | %d | %d | %d | %d | %d |\n\n",
		tot["equivalent"], tot["adaptation"], tot["extension"], tot["n/a"], tot["defect-not-copied"], tot["total"])

	for _, k := range kinds {
		n := 0
		for _, r := range m.Inventory {
			if r.Kind == k {
				n++
			}
		}
		fmt.Fprintf(&b, "## %s (%d)\n\n", k, n)
		b.WriteString("| ID | Surface | Disposition | xbps | Behaviour | Evidence | Spec | Test |\n")
		b.WriteString("|---|---|---|---|---|---|---|---|\n")
		for _, r := range m.Matrix {
			ir := inv[r.ID]
			if ir.Kind != k {
				continue
			}
			fmt.Fprintf(&b, "| %s | %s | %s | %s | %s | %s | %s | %s |\n",
				r.ID, esc(ir.Surface), r.Disposition, esc(r.Xbps), esc(r.Behaviour), esc(r.Evidence), esc(r.Spec), esc(r.Test))
		}
		b.WriteString("\n")
	}
	return b.String()
}

func (m *Matrix) Write(root string) error {
	specPath := filepath.Join(root, "xbpretty-spec.md")
	spec, err := os.ReadFile(specPath)
	if err != nil {
		return err
	}
	next, err := replaceRegion(string(spec), m.GenerateAppendix())
	if err != nil {
		return err
	}
	if err := os.WriteFile(specPath, []byte(next), 0o644); err != nil {
		return err
	}
	mdPath := filepath.Join(root, "docs/parity/matrix.md")
	if err := os.MkdirAll(filepath.Dir(mdPath), 0o755); err != nil {
		return err
	}
	return os.WriteFile(mdPath, []byte(m.GenerateMarkdown()), 0o644)
}

func (m *Matrix) CheckFresh(root string) error {
	spec, err := os.ReadFile(filepath.Join(root, "xbpretty-spec.md"))
	if err != nil {
		return err
	}
	want, err := replaceRegion(string(spec), m.GenerateAppendix())
	if err != nil {
		return err
	}
	if want != string(spec) {
		return fmt.Errorf("parity: xbpretty-spec.md Appendix A is stale: run make parity")
	}
	md, err := os.ReadFile(filepath.Join(root, "docs/parity/matrix.md"))
	if err != nil {
		return fmt.Errorf("parity: docs/parity/matrix.md is stale: run make parity (%v)", err)
	}
	if string(md) != m.GenerateMarkdown() {
		return fmt.Errorf("parity: docs/parity/matrix.md is stale: run make parity")
	}
	return nil
}

func replaceRegion(spec, generated string) (string, error) {
	start := strings.Index(spec, beginMarker)
	end := strings.Index(spec, endMarker)
	if start < 0 || end < 0 || end < start {
		return "", fmt.Errorf("parity: xbpretty-spec.md is missing the generated-parity markers")
	}
	return spec[:start] + generated + spec[end+len(endMarker):], nil
}
